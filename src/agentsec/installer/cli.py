"""agentsec install | preflight | validate | plan | rollback | print-config. Interactive when attached to a terminal (or --interactive); otherwise non-interactive
with a JSON configuration file and flags. Exit codes: 0 done, 2 usage or malformed configuration, 3 checks failed, 4 refused to overwrite, 6 apply failed."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Callable

from agentsec.installer import core, lifecycle, preflight as pf, provenance, render
from agentsec.installer.config import ACK_PHRASE, ACK_TEXT, ConfigError, InstallConfig, Locks, resolve_models

DEFAULT_FILE = "agentsec.install.json"
LIFECYCLE = ("up", "down", "status", "logs", "splunk-access")


def parse_sets(items: list[str], cfg_dict: dict) -> dict:
    """--set gateway.port=8000 / --set deployment=organization. Values: true/false, integers, otherwise text."""
    for item in items:
        if "=" not in item:
            raise ConfigError(f"--set expects key=value, got {item!r}")
        key, raw = item.split("=", 1)
        cur = cfg_dict
        parts = key.split(".")
        for p in parts[:-1]:
            cur = cur.setdefault(p, {})
            if not isinstance(cur, dict):
                raise ConfigError(f"--set {key}: {p} is not an object")
        cur[parts[-1]] = True if raw == "true" else False if raw == "false" else int(raw) if raw.lstrip("-").isdigit() else raw
    return cfg_dict


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="agentsec", description="AgentSec installer core: read-only checks, generated configuration, dry run. It never pulls images or touches containers unless --apply is given.")
    p.add_argument("command", choices=["install", "preflight", "validate", "plan", "rollback", "print-config", "verify-models", "verify-images", "up", "down", "status", "logs", "splunk-access"])
    p.add_argument("service", nargs="?", default="", help="logs: one Compose service (default: all)")
    p.add_argument("--root", default=".", help="the repository directory (default: current)")
    p.add_argument("--config", help=f"JSON configuration file (default: {DEFAULT_FILE} when it exists)")
    p.add_argument("--set", action="append", default=[], metavar="KEY=VALUE", help="override one setting, e.g. --set gateway.port=8000")
    p.add_argument("--non-interactive", action="store_true")
    p.add_argument("--interactive", action="store_true")
    p.add_argument("--dry-run", action="store_true", help="show what would be written and run; write nothing")
    p.add_argument("--apply", action="store_true", help="after writing, run the plan's docker compose commands (pull, up). Not used in tests.")
    p.add_argument("--accept-warnings", default="", help="comma-separated WARN codes to accept, or 'all'")
    p.add_argument("--ack-external-controls", action="store_true", help="organization mode: acknowledge that YOUR gateway enforces authentication, rate limiting and network access")
    p.add_argument("--execute", action="store_true", help="verify-images: actually query the registry (read-only); without it the queries are only listed")
    p.add_argument("--tail", type=int, default=100, help="logs: number of lines per service")
    p.add_argument("--follow", action="store_true", help="logs: keep streaming")
    p.add_argument("--access-auth", choices=["auto", "bearer", "basic"], default="auto", help="splunk-access: token if the KV store allows it, else the search-only user's password (auto); or force one")
    p.add_argument("--check", action="store_true", help="splunk-access: prove the provisioned access works, from the Attack Service (read-only)")
    p.add_argument("--force", action="store_true", help="splunk-access: renew even when access is already provisioned")
    p.add_argument("--force-env", action="store_true", help="replace an existing .env that was not generated by this installer (a backup is kept as .env.pre-agentsec)")
    return p


def load_config(args, root: Path) -> InstallConfig:
    path = Path(args.config) if args.config else (root / DEFAULT_FILE)
    data: dict = {}
    if path.is_file():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except ValueError as exc:
            raise ConfigError(f"{path.name} is not valid JSON ({exc})") from None
    elif args.config:
        raise ConfigError(f"configuration file {args.config!r} not found")
    data = parse_sets(args.set, data)
    if args.ack_external_controls:
        data["ack_external_controls"] = True
    return InstallConfig.from_dict(data)


def wizard(cfg_dict: dict, facts_hint: dict, ask: Callable[[str], str], say: Callable[[str], None]) -> dict:
    """One question at a time, a default in brackets. The wizard only fills the same dictionary a configuration file would contain."""
    def q(text: str, default: str, choices: tuple | None = None) -> str:
        while True:
            raw = ask(f"{text} [{default}]: ").strip() or default
            if choices is None or raw in choices:
                return raw
            say(f"  choose one of: {', '.join(choices)}")
    d = cfg_dict
    d["deployment"] = q("Deployment: localhost (this machine only) or organization (behind YOUR authentication / rate-limit / network gateway)", d.get("deployment", "localhost"), ("localhost", "organization"))
    if d["deployment"] == "organization":
        say("\n" + ACK_TEXT + "\n")
        d["ack_external_controls"] = ask(f"Type {ACK_PHRASE} to confirm that your gateway provides those controls: ").strip() == ACK_PHRASE
        d.setdefault("gateway", {})["bind"] = q("Address to publish on (0.0.0.0 = every interface; restrict with a firewall)", d.get("gateway", {}).get("bind", "0.0.0.0"))
    d.setdefault("gateway", {})["enabled"] = q("Use the lab's HTTPS gateway (recommended)", "yes" if d["gateway"].get("enabled", True) else "no", ("yes", "no")) == "yes"
    if d["gateway"]["enabled"]:
        d["gateway"]["host"] = q("Gateway host name", d["gateway"].get("host", "localhost"))
        d["gateway"]["port"] = int(q("Gateway port (443 or 8000)", str(d["gateway"].get("port", 443))))
    mac = facts_hint.get("platform") == "Darwin/arm64"
    d.setdefault("ollama", {})["mode"] = q("Ollama: bundled (container) or host (Ollama already running on this machine; recommended on Apple Silicon). Remote Ollama is not supported yet", ("host" if mac and d["ollama"].get("mode", "bundled") == "bundled" else d["ollama"].get("mode", "bundled")), ("bundled", "host"))
    d.setdefault("models", {})
    for role, label in (("pipeline", "AcmeBank labs"), ("loan_desk", "Loan Desk")):
        chosen = q(f"Model for the {label} (default = the locked default)", d["models"].get(role) or "default")
        d["models"][role] = "" if chosen == "default" else chosen
    d.setdefault("splunk", {})["mode"] = q("Splunk: bundled, external_enterprise, cloud, or none (replay only)", d["splunk"].get("mode", "bundled"), ("bundled", "external_enterprise", "cloud", "none"))
    if d["splunk"]["mode"] in ("external_enterprise", "cloud"):
        d["splunk"]["rest_url"] = q("Splunk REST URL (https://host:8089)", d["splunk"].get("rest_url", ""))
        ca = q("CA bundle file (absolute path, or 'system' for the system store)", d["splunk"].get("ca_file") or "system")
        d["splunk"]["ca_file"] = "" if ca == "system" else ca
        d["splunk"]["token_file"] = q("Search-only token file (absolute path; the token is never typed here)", d["splunk"].get("token_file", ""))
    return d


def summary(cfg: InstallConfig, plan: render.Plan, findings, say: Callable[[str], None], *, dry: bool) -> None:
    say(("DRY RUN: nothing is written or started.\n" if dry else "") + f"Project {cfg.project!r} ({cfg.naming} names), deployment {cfg.deployment}")
    for f in findings:
        if f.level != "OK":
            say("  " + f.line())
    say("Services: " + ", ".join(plan.services))
    say("Ports: " + ", ".join(f"{k} {v}" for k, v in plan.ports.items()))
    say("Writes: " + ", ".join(plan.files))
    for d in plan.downloads:
        say(f"Download on --apply: {d['what']} {d['ref']}")
    for n in plan.notes:
        say("Note: " + n)
    say("Commands on --apply:")
    for c in plan.commands:
        e = c.get("env") or {}
        say("  $ " + " ".join(f"{k}={v}" for k, v in e.items()) + (" " if e else "") + " ".join(c["argv"]))


def main(argv: list[str] | None = None, *, env: pf.Env | None = None, runner: core.Runner | None = None, ask: Callable[[str], str] = input,
         out: Callable[[str], None] = print, locks: Locks | None = None, isatty: bool | None = None) -> int:
    args = build_parser().parse_args(argv)
    root = Path(args.root).resolve()
    say = out
    env = env or pf.SystemEnv()
    locks = locks or Locks.load()
    try:
        if args.command == "rollback":
            restored = core.rollback(root)
            say("restored " + ", ".join(restored) if restored else "nothing to roll back (no previous configuration)")
            return core.EXIT_OK if restored else core.EXIT_CHECKS
        if args.command in LIFECYCLE:
            run = runner or core.SubprocessRunner()
            return {"up": lambda: lifecycle.up(root, locks, env, run, say), "down": lambda: lifecycle.down(root, env, run, say), "status": lambda: lifecycle.status(root, env, run, say),
                    "logs": lambda: lifecycle.logs(root, env, run, say, service=args.service, tail=args.tail, follow=args.follow),
                    "splunk-access": lambda: lifecycle.splunk_access_command(root, run, say, auth=args.access_auth, force=args.force, check=args.check)}[args.command]()
        cfg_dict_cfg = load_config(args, root)
        cfg = cfg_dict_cfg
        interactive = args.interactive or (not args.non_interactive and (sys.stdin.isatty() if isatty is None else isatty) and args.command == "install")
        if interactive:
            d = wizard(cfg.to_dict(), {"platform": "%s/%s" % env.platform_info()}, ask, say)
            cfg = InstallConfig.from_dict(d)
    except (ConfigError, ValueError) as exc:
        say(f"error: {exc}")
        return core.EXIT_USAGE
    if args.command == "print-config":
        say(json.dumps(cfg.to_dict(), indent=2, sort_keys=True))
        return core.EXIT_OK
    if args.command == "verify-images":
        plan_q = provenance.image_pin_plan(locks)
        if not args.execute:
            for item in plan_q:
                say(f"would run: {' '.join(item['argv'])}   (pinned: {item['expected'] or 'NOT PINNED'}, status {item['status']})")
            say("nothing was run; add --execute to query the registry (read-only)")
            return core.EXIT_OK
        run = (runner.run if runner else core.SubprocessRunner().run)
        res = provenance.verify_image_pins(locks, lambda argv: run(argv, str(root)))
        for f in res:
            say(f.line())
        return core.EXIT_CHECKS if any(f.level == "ERROR" for f in res) else core.EXIT_OK
    if args.command == "verify-models":
        models, _ = resolve_models(cfg, locks)
        url = {"host": "http://127.0.0.1:11434", "remote": cfg.ollama.url}.get(cfg.ollama.mode, "")
        if not url:
            say("INFO  the bundled Ollama is not reachable from the host (it publishes no port); verify with `docker compose exec ollama ollama list` or use host mode")
            return core.EXIT_OK
        res = provenance.verify_models(locks, models, env.ollama_tags(url))
        for f in res:
            say(f.line())
        return core.EXIT_CHECKS if any(f.level == "ERROR" for f in res) else core.EXIT_OK
    findings, facts = core.collect(cfg, locks, env, root)
    facts["gateway_dir_exists"] = bool(env.path_info(str(root / ".gateway")))
    accept = {c.strip() for c in args.accept_warnings.split(",") if c.strip()}
    errors, warns = core.gate(findings, accept)
    prev_env, ours = core.read_env(root)
    plan = render.build_plan(cfg, locks, facts, prev_env if ours else None)
    if args.command in ("preflight", "validate"):
        for f in findings:
            say(f.line())
        return core.EXIT_CHECKS if errors else core.EXIT_OK
    dry = args.dry_run or args.command == "plan"
    summary(cfg, plan, findings, say, dry=dry)
    if errors:
        say(f"FAIL  {len(errors)} error(s): nothing was written.")
        return core.EXIT_CHECKS
    if warns:
        say("FAIL  unaccepted warnings (re-run with --accept-warnings " + ",".join(sorted({w.code for w in warns})) + " or all): nothing was written.")
        return core.EXIT_CHECKS
    if dry:
        return core.EXIT_OK
    if (root / ".env").is_file() and not ours and not args.force_env:
        say("REFUSED  .env exists and was not generated by this installer. Re-run with --force-env to replace it (a backup is kept as .env.pre-agentsec).")
        return core.EXIT_REFUSED
    if (root / ".env").is_file() and not ours:
        say("kept your .env as " + core.backup_foreign_env(root))
    try:
        written = core.write_files(root, plan)
    except OSError as exc:
        say(f"REFUSED  {exc}")
        return core.EXIT_REFUSED
    say("wrote " + ", ".join(written) if written else "nothing changed: the generated files already match this configuration")
    if args.apply:
        run = runner or core.SubprocessRunner()
        rc = core.apply(plan, run, root, say)
        if rc == core.EXIT_OK:
            state, _ = lifecycle.load_state(root)
            if state is not None:
                lifecycle.provision_access(root, state, run, say)      # fail-soft: never changes the exit code
        return rc
    say("Next: review the plan above, then run again with --apply (or run the commands yourself).")
    return core.EXIT_OK


if __name__ == "__main__":
    raise SystemExit(main())
