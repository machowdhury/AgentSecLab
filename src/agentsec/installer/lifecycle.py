"""agentsec up | down | status | logs: operate the installation described by .agentsec/install.json. Containers are addressed only through Docker Compose (project,
files and profiles come from the generated state, never from fixed container names). Safety rules, each enforced in code and tested:
  * `down` removes containers and the network only. No volume, image or orphan is ever removed (`safe` refuses any such argument).
  * `up` validates configuration, file permissions, image pins and prerequisites BEFORE starting anything, and never recreates an existing container.
  * every operation is idempotent; a failure never deletes or rolls back anything (the generated files are untouched, running containers keep running).
All machine effects go through the injected Env (read) and Runner (execute)."""
from __future__ import annotations

import hashlib
import json
import os
import re
import stat
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from agentsec.installer import preflight as pf, render, splunk_access
from agentsec.installer.config import ENV_SAFE, managed_access, PROJECT_RE, ConfigError, Finding, InstallConfig, Locks, ollama_image, splunk_image, validate
from agentsec.installer.core import _write_private, EXIT_APPLY, EXIT_CHECKS, EXIT_OK, EXIT_USAGE, Runner, read_env

EXIT_NOT_READY = 5
FORBIDDEN = {"-v", "-V", "--volumes", "--renew-anon-volumes", "--force-recreate", "--build", "--rmi", "--remove-orphans", "prune", "rm", "volume", "system", "kill"}   # never part of a lifecycle command
SECRET_KEYS = ("SPLUNK_PASSWORD", "SPLUNK_HEC_TOKEN")
STOP_TIMEOUT = "120"      # Splunk needs time to shut down cleanly; the Compose default of 10 s risks the indexed data


@dataclass
class State:
    cfg: InstallConfig
    project: str
    services: list
    files: dict          # relative path -> sha256 recorded when the files were generated
    images: dict
    env: dict            # parsed .env


def load_state(root: Path) -> tuple[State | None, list[Finding]]:
    """The installation state, or (None, findings) explaining why there is none. Never raises on bad input."""
    st = root / render.STATE_DIR / "install.json"
    if (root / render.STATE_DIR).is_symlink() or st.is_symlink() or not st.is_file():
        return None, [Finding("ERROR", "NOT_INSTALLED", f"no installation found in {root} ({render.STATE_DIR}/install.json is missing): run `./agentsec install` first")]
    try:
        data = json.loads(st.read_text(encoding="utf-8"))
        if data.get("schema") != 1:
            raise ValueError("unsupported schema")
        cfg = InstallConfig.from_dict(data["config"])
        res = data["resolved"]
        files, images = dict(data["files"]), dict(res.get("images", {}))
    except (ValueError, KeyError, TypeError, AttributeError, ConfigError) as exc:
        return None, [Finding("ERROR", "STATE_UNREADABLE", f"{render.STATE_DIR}/install.json cannot be used ({type(exc).__name__}); re-run `./agentsec install` (data volumes are not touched)")]
    env, ours = read_env(root)
    if not ours:
        return None, [Finding("ERROR", "ENV_NOT_GENERATED", ".env is missing or was not generated by the installer: re-run `./agentsec install`")]
    # install.json is editable, so nothing in it is trusted for building commands: the project must be valid and equal the one in .env, and the service list
    # is recomputed from the configuration (never read from the state)
    if not PROJECT_RE.fullmatch(cfg.project or "") or env.get("COMPOSE_PROJECT_NAME") != cfg.project:
        return None, [Finding("ERROR", "STATE_PROJECT_MISMATCH", f"the project in {render.STATE_DIR}/install.json does not match the generated .env (or is not a valid project name): re-run `./agentsec install`")]
    return State(cfg, cfg.project, render.services(cfg), files, images, env), []


def _compose(root: Path, state: State, *args: str) -> dict:
    """One docker compose invocation. The project, file list and profiles are passed explicitly (flags and process environment) so a stale COMPOSE_* variable
    in the caller's shell cannot redirect the command to another project."""
    e = state.env
    env = dict(e)      # the whole generated .env as process environment: variables exported in the caller's shell would otherwise beat .env values (bind address, ports)
    return {"argv": ["docker", "compose", "--project-name", state.project, "--env-file", str(root / ".env"), *args], "env": env}


def safe(cmd: dict) -> dict:
    bad = FORBIDDEN & set(cmd["argv"])
    if bad:
        raise AssertionError(f"refusing a lifecycle command containing {sorted(bad)}")
    return cmd


def ctf_findings(root: Path, state: State) -> list[Finding]:
    """The CTF secret is for one runtime identity: the unprivileged user that installed the lab. Anything else fails closed with the fix in the message."""
    uid, out = os.getuid(), []
    err = lambda c, m: out.append(Finding("ERROR", c, m))
    if uid == 0:
        err("CTF_AS_ROOT", "the CTF gateway secret belongs to the unprivileged installing user; run `./agentsec` without sudo (add the user to the docker group)")
        return out
    if state.env.get("AGENTSEC_CTF_UID") != str(uid):
        err("CTF_UID_MISMATCH", f"this lab was installed by uid {state.env.get('AGENTSEC_CTF_UID')}, you are uid {uid}: run as the installing user, or re-run `./agentsec install` as yourself (delete .gateway/ctf-* first to rotate the secret)")
    g = root / ".gateway"
    for name, is_dir in (("ctf-gateway-secret", False), ("ctf-secret.conf", False), ("ctf-state", True)):
        p = g / name
        try:
            st = p.lstat()
        except OSError:
            err("CTF_SECRET_MISSING", f".gateway/{name} is missing: run `sh scripts/gateway.sh ctf-enable` as the installing user")
            continue
        if stat.S_ISLNK(st.st_mode) or stat.S_ISDIR(st.st_mode) != is_dir or st.st_uid != uid or st.st_mode & 0o077:
            err("CTF_SECRET_PERMISSIONS", f".gateway/{name} must be a real {'directory' if is_dir else 'file'} owned by uid {uid} with no group or other access (mode {'0700' if is_dir else '0600'}); fix it or delete the ctf-* files and run `sh scripts/gateway.sh ctf-enable`")
    try:
        if not re.fullmatch(r"[0-9a-f]{64}", (g / "ctf-gateway-secret").read_text().strip()):
            err("CTF_SECRET_FORMAT", ".gateway/ctf-gateway-secret is not 64 lowercase hex characters: delete it and run `sh scripts/gateway.sh ctf-enable`")
    except OSError:
        pass
    return out


def check_ready(root: Path, state: State, locks: Locks, env: pf.Env) -> list[Finding]:
    """Everything that must hold before `up` starts anything. ERROR findings block."""
    f: list[Finding] = []
    err = lambda c, m: f.append(Finding("ERROR", c, m))
    cfg = state.cfg
    f += [x for x in validate(cfg, locks) if x.level == "ERROR"]
    if cfg.gateway.enabled and cfg.gateway.ctf:
        f += ctf_findings(root, state)
    # generated files: present, regular, owner-only, unmodified
    sd = root / render.STATE_DIR
    for rel, digest in state.files.items():
        p = root / rel
        if p.is_symlink() or not p.is_file():
            err("GENERATED_FILE_MISSING", f"{rel} is missing or is not a regular file: re-run `./agentsec install`")
            continue
        if hashlib.sha256(p.read_bytes()).hexdigest() != digest:
            err("GENERATED_FILE_MODIFIED", f"{rel} changed since it was generated; edit agentsec.install.json and re-run `./agentsec install` instead of editing generated files")
    for p, limit in ((root / ".env", 0o077), (sd, 0o077)):
        try:
            mode = p.stat().st_mode & 0o777
        except OSError:
            continue
        if mode & limit:
            err("PERMISSIONS_TOO_OPEN", f"{p.name} is accessible to other users (mode {mode:o}); run: chmod {'700' if p.is_dir() else '600'} {p}")
    for k in SECRET_KEYS:
        if not ENV_SAFE.fullmatch(state.env.get(k, "")) or not state.env.get(k):
            err("SECRET_FORMAT", f"{k} in .env is empty or contains characters Compose would interpolate ($, #, quotes, spaces): re-run `./agentsec install`")
    # the generated files must be exactly what the validated configuration renders to (the hashes live in the editable state file, so they prove nothing alone)
    try:
        sec = {k: state.env.get(k, "") for k in SECRET_KEYS}
        if (root / ".env").read_text(errors="replace") != render.render_env(render.env_values(cfg, locks, sec)):
            err("GENERATED_FILE_MODIFIED", ".env differs from what agentsec.install.json renders to: re-run `./agentsec install`")
        ov = root / render.STATE_DIR / "compose.override.yml"
        if ov.is_file() and ov.read_text(errors="replace") != render.render_override(cfg):
            err("GENERATED_FILE_MODIFIED", f"{render.STATE_DIR}/compose.override.yml differs from what the configuration renders to: re-run `./agentsec install`")
    except (OSError, KeyError):
        pass          # missing files are reported above
    # image pins: what the state recorded must still be what the reviewed locks say, and a release-mode install needs digests
    want = {}
    if cfg.splunk.mode == "bundled":
        want["splunk"] = splunk_image(cfg, locks)[0]
    if cfg.ollama.mode == "bundled":
        want["ollama"] = ollama_image(cfg, locks)[0]
    for name, ref in want.items():
        if state.images.get(name) != ref:
            err("IMAGE_PIN_CHANGED", f"the {name} image in the install state ({state.images.get(name)!r}) differs from deploy/images.lock.json ({ref!r}); re-run `./agentsec install` to review the change")
        if cfg.require_digests and "@sha256:" not in ref:
            err("IMAGE_NOT_PINNED", f"{name} image {ref!r} has no digest and require_digests is set")
    # prerequisites and machine state (Docker, Compose, ports, existing containers, Ollama): the same read-only checks as install
    pre, _ = pf.preflight(cfg, locks, env, install_dir=str(root))
    # an unchanged Splunk image over this project's own existing Splunk container is not an upgrade (without this a fresh 10.6 install could never be restarted)
    same = _started_splunk(root) == state.images.get("splunk") is not None
    f += [x for x in pre if x.level in ("ERROR", "WARN") and not (same and x.code in ("SPLUNK_UPGRADE_BLOCKED", "SPLUNK_UPGRADE_NEEDS_ACK"))]
    return f


def _started_splunk(root: Path):
    """The Splunk image of the last successful `up` (the data volumes belong to it), or None."""
    try:
        return json.loads((root / render.STATE_DIR / "started.json").read_text()).get("splunk")
    except (OSError, ValueError, AttributeError):
        return None


def _redact(text: str, state: State) -> str:
    for k in SECRET_KEYS:
        v = state.env.get(k)
        if v:
            text = text.replace(v, "***")
    return text


def _need_docker(env: pf.Env, say) -> bool:
    if env.docker_info() is None:
        say("FAIL  Docker is not installed or its daemon is not running: start Docker Desktop / the Docker service and retry")
        return False
    return True


def up(root: Path, locks: Locks, env: pf.Env, runner: Runner, say: Callable[[str], None]) -> int:
    state, bad = load_state(root)
    if state is None:
        for b in bad:
            say(b.line())
        return EXIT_USAGE
    findings = check_ready(root, state, locks, env)
    for x in findings:
        say(x.line())
    if any(x.level == "ERROR" for x in findings):
        say("FAIL  not started: fix the errors above (nothing was changed).")
        return EXIT_CHECKS
    cmds = [_compose(root, state, "config", "-q")] + render.prestart_commands(state.cfg, bool(env.path_info(str(root / ".gateway")))) + \
           [_compose(root, state, "up", "-d", "--no-recreate", *state.services)]      # --no-recreate: an existing container (and its data) is never replaced by `up`
    for c in cmds:
        safe(c)
        rc, out = runner.run(c["argv"], str(root), c["env"])
        if rc != 0:
            say(f"FAIL  `{' '.join(c['argv'][:2] + [a for a in c['argv'] if a in ('config', 'up', 'mkdir', 'sh')][:1])}` exited {rc}: {_redact(out, state).strip()[-400:]}")
            say("Nothing was removed or rolled back; containers that did start keep running and no data was touched. Fix the cause and run `./agentsec up` again (it is safe to repeat), or `./agentsec down`.")
            return EXIT_APPLY
    if state.images.get("splunk"):
        _write_private(root / render.STATE_DIR / "started.json", json.dumps({"splunk": state.images["splunk"]}) + "\n")
    provision_access(root, state, runner, say)
    say(f"OK    project {state.project!r} is up ({len(state.services)} services). Check it with `./agentsec status`. Containers that already existed keep their old settings: after changing ports or the bind address run `./agentsec down` then `./agentsec up` (data volumes are kept).")
    return EXIT_OK


def provision_access(root: Path, state: State, runner: Runner, say: Callable[[str], None], *, auth: str = "auto", wait_s: int = 600, force: bool = False) -> bool:
    """Provision least-privilege Splunk search access for the Attack Service (installer-managed, bundled Splunk). Never fatal: when it cannot be done the lab runs and
    search access reads UNAVAILABLE. Skipped when it is already provisioned (unless forced) or not applicable. Returns True when access is in place."""
    if not managed_access(state.cfg):
        say("INFO  Splunk search access is not installer-managed here (splunk.access is off, or REST settings were given by hand).")
        return False
    if not force and splunk_access.read_status(root) is not None:
        say("OK    Splunk search access files are present (`./agentsec splunk-access --check` proves they work; `--force` renews them).")
        return True
    def compose(args: list) -> tuple[int, str]:
        c = safe(_compose(root, state, *args))
        return runner.run(c["argv"], str(root), c["env"])
    return splunk_access.provision(root, compose, say, index=state.cfg.splunk.index, auth=auth, wait_s=wait_s)


def down(root: Path, env: pf.Env, runner: Runner, say: Callable[[str], None]) -> int:
    state, bad = load_state(root)
    if state is None:
        for b in bad:
            say(b.line())
        return EXIT_USAGE
    if not _need_docker(env, say):
        return EXIT_CHECKS
    c = safe(_compose(root, state, "down", "--timeout", STOP_TIMEOUT))
    rc, out = runner.run(c["argv"], str(root), c["env"])
    if rc != 0:
        say(f"FAIL  docker compose down exited {rc}: {_redact(out, state).strip()[-400:]}")
        say("Nothing else was changed. It is safe to run `./agentsec down` again.")
        return EXIT_APPLY
    say(f"OK    project {state.project!r} is down: containers and network removed. Volumes (Splunk data, models, app, telemetry) are kept; `./agentsec up` reattaches them.")
    return EXIT_OK


def _services_table(out: str) -> list[dict]:
    """`docker compose ps --all --format json` prints one JSON object per line (older Compose: one array)."""
    out = out.strip()
    if not out:
        return []
    try:
        data = json.loads(out)
        return data if isinstance(data, list) else [data]
    except ValueError:
        rows = []
        for line in out.splitlines():
            try:
                rows.append(json.loads(line))
            except ValueError:
                continue
        return rows


def status(root: Path, env: pf.Env, runner: Runner, say: Callable[[str], None]) -> int:
    """Read-only. Exit 0 when every expected service is running (the init jobs must have exited 0), 5 when something is missing or unhealthy."""
    state, bad = load_state(root)
    if state is None:
        for b in bad:
            say(b.line())
        return EXIT_USAGE
    if not _need_docker(env, say):
        return EXIT_CHECKS
    c = safe(_compose(root, state, "ps", "--all", "--format", "json"))
    rc, out = runner.run(c["argv"], str(root), c["env"])
    if rc != 0:
        say(f"FAIL  docker compose ps exited {rc}: {_redact(out, state).strip()[-300:]}")
        return EXIT_APPLY
    rows = {r.get("Service"): r for r in _services_table(out)}
    ok = True
    for name in state.services:
        r = rows.get(name)
        once = name in ("splunk_app_init", "splunk_hec_init")
        if r is None:
            ok, line = False, "MISSING     not created: run `./agentsec up`"
        else:
            s, h, code = r.get("State", "?"), r.get("Health") or "", r.get("ExitCode", 0)
            good = (s == "exited" and code == 0) if once else (s == "running" and h in ("", "healthy"))
            ok &= good
            line = f"{'OK' if good else 'NOT READY':<11} {s}{'/' + h if h else ''}" + (f" (exit {code})" if s == "exited" else "")
        say(f"  {name:<16} {line}")
    say(f"{'OK' if ok else 'FAIL'}    project {state.project!r}: " + ("all services are up." if ok else "not all services are ready (a first Splunk start can take several minutes)."))
    if managed_access(state.cfg):
        meta = splunk_access.read_status(root)
        say("  splunk search access: " + (f"files present ({meta['auth']}); prove it with `./agentsec splunk-access --check`" if meta else "NOT PROVISIONED (notebook and verification say unavailable): run `./agentsec splunk-access`"))
    return EXIT_OK if ok else EXIT_NOT_READY


def logs(root: Path, env: pf.Env, runner: Runner, say: Callable[[str], None], *, service: str = "", tail: int = 100, follow: bool = False) -> int:
    state, bad = load_state(root)
    if state is None:
        for b in bad:
            say(b.line())
        return EXIT_USAGE
    if service and service not in state.services:
        say(f"error: unknown service {service!r}; this installation has: {', '.join(state.services)}")
        return EXIT_USAGE
    if not 1 <= tail <= 100000:
        say("error: --tail must be between 1 and 100000")
        return EXIT_USAGE
    if not _need_docker(env, say):
        return EXIT_CHECKS
    args = ["logs", "--no-color", "--tail", str(tail)] + (["--follow"] if follow else []) + ([service] if service else [])
    c = safe(_compose(root, state, *args))
    if follow:
        rc = runner.stream(c["argv"], str(root), c["env"])      # the output goes straight to the terminal; secrets are not redacted here
        return EXIT_OK if rc in (0, 130) else EXIT_APPLY
    rc, out = runner.run(c["argv"], str(root), c["env"])
    say(_redact(out, state).rstrip("\n"))
    return EXIT_OK if rc == 0 else EXIT_APPLY


def check_access(root: Path, state: State, runner: Runner, say: Callable[[str], None]) -> bool:
    """A live proof from where it matters: the Attack Service's own REST client, with the mounted files, against Splunk (the five stages). Files being present proves nothing:
    a wiped Splunk volume or an expired token leaves them in place."""
    c = safe(_compose(root, state, "exec", "-T", "attack_service", "python", "-m", "agentsec.splunk_client", "check"))
    rc, out = runner.run(c["argv"], str(root), c["env"])
    lines = [ln.strip() for ln in out.splitlines() if re.match(r"^(CONNECTIVITY|AUTHENTICATION|AUTHORIZATION|SEARCH|TELEMETRY) ", ln.strip())]
    for ln in lines:
        say("      " + ln)
    ok = rc == 0 and any(ln.startswith("SEARCH PASS") for ln in lines)
    say("OK    Splunk search access works from the Attack Service." if ok else "FAIL  Splunk search access does not work from the Attack Service: run `./agentsec splunk-access --force` (the notebook says 'unavailable' until it does).")
    return ok


def splunk_access_command(root: Path, runner: Runner, say: Callable[[str], None], *, auth: str = "auto", force: bool = False, check: bool = False) -> int:
    """`agentsec splunk-access`: provision (or renew) the Attack Service's search access, then show its state. Exit 0 when provisioned, 5 when not."""
    state, bad = load_state(root)
    if state is None:
        for b in bad:
            say(b.line())
        return EXIT_USAGE
    if check:
        return EXIT_OK if check_access(root, state, runner, say) else EXIT_NOT_READY
    ok = provision_access(root, state, runner, say, auth=auth, force=force)
    meta = splunk_access.read_status(root)
    if meta:
        say(f"      auth {meta['auth']}, user {meta['user']}, provisioned {meta['provisioned_at']}" + (f", token valid {meta['token_expires']}" if meta.get("token_expires") else "")
            + (f", password because: {meta['fallback']}" if meta.get("fallback") else ""))
    return EXIT_OK if ok else EXIT_NOT_READY
