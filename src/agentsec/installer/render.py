"""Generated configuration: the `.env`, the Compose override, the installer state, the plan. Pure functions of (config, locks, facts, previous secrets): the same input
always yields the same text, so a dry run shows exactly what a real run would write. Secrets are generated here only when none exist yet; an existing install's
secrets are REUSED (rotating the Splunk password would not change an existing Splunk volume and would break the lab)."""
from __future__ import annotations

import hashlib
import json
import os
import re
import secrets
import uuid
from dataclasses import dataclass, field

from agentsec import model_names
from agentsec.installer.config import InstallConfig, Locks, managed_access, ollama_image, resolve_models, rest_enabled, splunk_image

MARKER = "# generated by the AgentSec installer (agentsec install). Edit agentsec.install.json and re-run instead of editing this file."
STATE_DIR = ".agentsec"
INSTALLER_VERSION = "0.1"
BASE_SERVICES = ["acmebank", "attack_service", "otel_collector"]
LEGACY_NAME = {"ollama": "agentsec_ollama", "acmebank": "agentsec_acmebank", "attack_service": "agentsec_attack_service", "otel_collector": "agentsec_otel_collector",
               "splunk": "agentsec_splunk", "splunk_app_init": "agentsec_splunk_app_init", "splunk_hec_init": "agentsec_splunk_hec_init", "gateway": "agentsec_gateway"}
DEFAULT_PORTS = {"splunk_web": 8000, "hec": 8088, "otel_grpc": 4317, "otel_http": 4318, "acmebank": 5000, "attack": 5001}
ENV_KEY = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$")


def services(cfg: InstallConfig) -> list[str]:
    s = list(BASE_SERVICES)
    if cfg.ollama.mode == "bundled":
        s.insert(0, "ollama")
    if cfg.splunk.mode == "bundled":
        s += ["splunk_app_init", "splunk_hec_init", "splunk"]
    if cfg.gateway.enabled:
        s.append("gateway")
    return s


def generate_secrets(previous_env: dict | None = None) -> dict:
    """SPLUNK_PASSWORD and SPLUNK_HEC_TOKEN. Reused from an installer-generated .env when present; random otherwise (never the old example defaults)."""
    prev = previous_env or {}
    reusable = lambda k: prev.get(k) if prev.get(k) and prev.get(k) not in ("ChangeMeLab!2026", "lab-hec-token-change-me") else None
    return {"SPLUNK_PASSWORD": reusable("SPLUNK_PASSWORD") or ("Sp" + secrets.token_hex(10) + "A1"),
            "SPLUNK_HEC_TOKEN": reusable("SPLUNK_HEC_TOKEN") or str(uuid.UUID(bytes=secrets.token_bytes(16), version=4))}


def parse_env(text: str) -> dict:
    out = {}
    for line in text.splitlines():
        m = ENV_KEY.match(line.strip()) if not line.lstrip().startswith("#") else None
        if m:
            out[m.group(1)] = m.group(2)
    return out


def _splunk_web_port(cfg: InstallConfig) -> int:
    # in gateway mode Splunk Web moves off 8000 (the optional public port) to a loopback-only port
    return 18000 if cfg.gateway.enabled and cfg.ports.splunk_web == 8000 else cfg.ports.splunk_web


def env_values(cfg: InstallConfig, locks: Locks, sec: dict) -> dict:
    """Ordered dict of the .env keys. No value here is a secret except those in `sec`."""
    models, _ = resolve_models(cfg, locks)
    v: dict = {}
    v["COMPOSE_PROJECT_NAME"] = cfg.project
    files = ["docker-compose.yml"]
    profiles = []
    if cfg.splunk.mode == "bundled":
        files.append("docker-compose.local.yml"); profiles.append("local")
    if cfg.gateway.enabled:
        files.append("docker-compose.gateway.yml"); profiles.append("gateway")
        if cfg.gateway.ctf:
            files.append("docker-compose.gateway-ctf.yml")       # the CTF overlay: secret, state volume and runtime user (see CTF.md)
    files.append(f"{STATE_DIR}/compose.override.yml")
    v["COMPOSE_FILE"] = ":".join(files)
    v["COMPOSE_PROFILES"] = ",".join(profiles)
    v.update(AGENTSEC_SECURITY_PROFILE="defended", AGENTSEC_LAB_ID="agentsec-local", AGENTSEC_TESTBED_MODE="auto", AGENTSEC_OTEL_ENABLED="true")
    v["OLLAMA_MODEL"], v["LOANDESK_MODEL"] = models.get("pipeline", ""), models.get("loan_desk", "")
    if cfg.ollama.mode == "host":
        v["OLLAMA_BASE_URL"] = "http://host.docker.internal:11434"
    elif cfg.ollama.mode == "remote":
        v["OLLAMA_BASE_URL"] = cfg.ollama.url
    v["AGENTSEC_BIND_ADDRESS"] = _bind(cfg)
    v["SPLUNK_PASSWORD"], v["SPLUNK_HEC_TOKEN"] = sec["SPLUNK_PASSWORD"], sec["SPLUNK_HEC_TOKEN"]
    if cfg.splunk.mode == "bundled":
        ref, _, _ = splunk_image(cfg, locks)
        v["SPLUNK_IMAGE"], v["SPLUNK_PLATFORM"] = ref, locks.images["splunk"]["platform"]
    v.update(AGENTSEC_HEC_TLS_MODE="LOCAL_SELF_SIGNED", SPLUNK_HEC_ENDPOINT="https://agentsec_splunk:8088/services/collector/event",
             SPLUNK_HEC_INDEX="agentsec_telemetry", SPLUNK_HEC_SOURCETYPE="otel:agentic:json", SPLUNK_HEC_SOURCE="agentsec-otel-collector")
    if rest_enabled(cfg.splunk):
        v.update(AGENTSEC_SPLUNK_MODE=cfg.splunk.mode.upper(), AGENTSEC_SPLUNK_REST_URL=cfg.splunk.rest_url, AGENTSEC_SPLUNK_CA_BUNDLE_FILE=cfg.splunk.ca_file,
                 AGENTSEC_SPLUNK_SEARCH_TOKEN_FILE=cfg.splunk.token_file, AGENTSEC_SPLUNK_INDEX=cfg.splunk.index)
    if cfg.gateway.enabled:
        v.update(AGENTSEC_PUBLIC_HOST=cfg.gateway.host, AGENTSEC_PUBLIC_PORT=str(cfg.gateway.port), AGENTSEC_GATEWAY_BIND=_addr(cfg.gateway.bind),
                 AGENTSEC_TLS_MODE="LOCAL_DEV", AGENTSEC_SPLUNK_LOCAL_PORT=str(_splunk_web_port(cfg)), AGENTSEC_ATTACK_TIER="enabled")
        if cfg.gateway.ctf:
            # the Attack Service runs as the installing user so it can read the 0600 secret that user owns; never root, never a guessed uid
            v.update(AGENTSEC_CTF_GATEWAY="enabled", AGENTSEC_CTF_SECRET_FILE="./.gateway/ctf-gateway-secret", AGENTSEC_CTF_SECRET_CONF="./.gateway/ctf-secret.conf",
                     AGENTSEC_CTF_STATE_HOST="./.gateway/ctf-state", AGENTSEC_CTF_UID=str(os.getuid()), AGENTSEC_CTF_GID=str(os.getgid()))
        if cfg.gateway.bind not in ("127.0.0.1", "::1", "localhost"):
            v["AGENTSEC_GATEWAY_ALLOW_NONLOOPBACK"] = "1"      # only reachable when organization mode was acknowledged (validate refuses otherwise)
    return v


def render_env(values: dict) -> str:
    return MARKER + "\n" + "".join(f"{k}={val}\n" for k, val in values.items())


SPLUNK_TOKEN_IN_CONTAINER, SPLUNK_CA_IN_CONTAINER = "/run/secrets/agentsec_splunk_token", "/run/secrets/agentsec_splunk_ca"


def _splunk_rest_lines(cfg: InstallConfig) -> list[str]:
    """The Attack Service verifies evidence over Splunk REST, so it needs the settings AND the files inside its container. Compose did not pass them before
    (the .env values were only read by host scripts), so the check could never run there. The token and CA are bind-mounted read-only at fixed paths; the
    host paths come from validated configuration and are quoted as JSON strings, which are valid YAML."""
    s = cfg.splunk
    env = {"AGENTSEC_SPLUNK_MODE": s.mode.upper(), "AGENTSEC_SPLUNK_REST_URL": s.rest_url, "AGENTSEC_SPLUNK_INDEX": s.index,
           "AGENTSEC_SPLUNK_SEARCH_TOKEN_FILE": SPLUNK_TOKEN_IN_CONTAINER}
    mounts = [(s.token_file, SPLUNK_TOKEN_IN_CONTAINER)]
    if s.ca_file:
        env["AGENTSEC_SPLUNK_CA_BUNDLE_FILE"] = SPLUNK_CA_IN_CONTAINER
        mounts.append((s.ca_file, SPLUNK_CA_IN_CONTAINER))
    out = ["    environment:"] + [f"      - {json.dumps(f'{k}={v}')}" for k, v in env.items()] + ["    volumes:"]
    for src, dst in mounts:
        out += ["      - type: bind", f"        source: {json.dumps(src)}", f"        target: {dst}", "        read_only: true"]
    return out


def _splunk_access_lines(cfg: InstallConfig) -> list[str]:
    """Installer-managed search access: the directory the provisioning step fills is mounted read-only; the client reads it on every request, so no restart
    is needed after provisioning. Without the files, search is unavailable (fail closed)."""
    from agentsec.installer.splunk_access import ACCESS_DIR, CONTAINER_DIR, REST_URL
    env = {"AGENTSEC_SPLUNK_MODE": "BUNDLED", "AGENTSEC_SPLUNK_REST_URL": REST_URL, "AGENTSEC_SPLUNK_INDEX": cfg.splunk.index, "AGENTSEC_SPLUNK_ACCESS_DIR": CONTAINER_DIR}
    return (["    environment:"] + [f"      - {json.dumps(f'{k}={v}')}" for k, v in env.items()] +
            ["    volumes:", "      - type: bind", f"        source: {json.dumps('./' + ACCESS_DIR)}", f"        target: {CONTAINER_DIR}", "        read_only: true"])


def render_override(cfg: InstallConfig) -> str:
    """The Compose override: project-scoped container names (with the old agentsec_* names kept as network aliases so in-mesh DNS names still resolve),
    host ports where they differ from the defaults, LOANDESK_MODEL passed to AcmeBank (the base file never passed it), and no dependency on the bundled Ollama
    when Ollama is on the host or remote. Hand-written YAML on purpose (stdlib only); every value is validated or generated, never free text."""
    svc = services(cfg)
    out = ["# " + MARKER[2:], "services:"]
    p = cfg.ports
    gw = cfg.gateway.enabled
    for name in svc:
        lines: list[str] = []
        if cfg.naming == "project":
            lines.append(f"    container_name: {cfg.project}-{name.replace('_', '-')}")
            lines += ["    networks:", "      agentsec_mesh:", "        aliases:", f"          - {LEGACY_NAME[name]}"]
        if name == "acmebank":
            lines += ["    environment:", f"      - LOANDESK_MODEL=${{LOANDESK_MODEL:-{model_names.default_for('loan_desk')}}}"]
            if cfg.ollama.mode != "bundled":
                lines += ["    depends_on: !override", "      otel_collector:", "        condition: service_started"]
                if cfg.ollama.mode == "host":
                    lines += ["    extra_hosts:", '      - "host.docker.internal:host-gateway"']
            if not gw and p.acmebank != DEFAULT_PORTS["acmebank"]:
                lines += ["    ports: !override", f'      - "{_bind(cfg)}:{p.acmebank}:5000"']
        elif name == "attack_service":
            if rest_enabled(cfg.splunk):
                lines += _splunk_rest_lines(cfg)
            elif managed_access(cfg):
                lines += _splunk_access_lines(cfg)
            if not gw and p.attack != DEFAULT_PORTS["attack"]:
                lines += ["    ports: !override", f'      - "{_bind(cfg)}:{p.attack}:5001"']
        elif name == "otel_collector":
            if (p.otel_grpc, p.otel_http) != (DEFAULT_PORTS["otel_grpc"], DEFAULT_PORTS["otel_http"]):
                lines += ["    ports: !override", f'      - "127.0.0.1:{p.otel_grpc}:4317"', f'      - "127.0.0.1:{p.otel_http}:4318"']
        elif name == "splunk":
            web = _splunk_web_port(cfg)
            lines += ["    stop_grace_period: 120s"]          # Splunk needs time to shut down cleanly; the 10 s default risks the data
            if web != (18000 if gw else DEFAULT_PORTS["splunk_web"]) or p.hec != DEFAULT_PORTS["hec"]:
                web_bind = "127.0.0.1" if gw else _bind(cfg)      # the base file publishes Splunk Web on the learner bind address; the gateway moves it to loopback
                lines += ["    ports: !override", f'      - "{web_bind}:{web}:8000"', f'      - "127.0.0.1:{p.hec}:8088"']
        if lines:
            out += [f"  {name}:"] + lines
    return "\n".join(out) + "\n"


def _addr(a: str) -> str:
    """An address as Docker's port syntax wants it: no `localhost`, IPv6 in brackets."""
    return "127.0.0.1" if a == "localhost" else f"[{a}]" if ":" in a else a


def _bind(cfg: InstallConfig) -> str:
    return _addr(cfg.gateway.bind) if cfg.deployment == "organization" else "127.0.0.1"


@dataclass
class Plan:
    files: dict                                   # relative path -> text
    secret_files: list = field(default_factory=list)
    commands: list = field(default_factory=list)  # {"argv": [...], "env": {...}} executed only by apply
    downloads: list = field(default_factory=list)
    services: list = field(default_factory=list)
    ports: dict = field(default_factory=dict)
    notes: list = field(default_factory=list)


def prestart_commands(cfg: InstallConfig, gateway_dir_exists: bool) -> list:
    """Host-side preparation that must precede `compose up`; shared by `install --apply` and `agentsec up`. All of it is idempotent."""
    cmd = lambda *argv, **env: {"argv": list(argv), "env": env}
    out = [cmd("mkdir", "-p", "artifacts/loan_desk/receipts")]      # the receipts directory must exist before the read-only mount
    if managed_access(cfg):
        out += [cmd("mkdir", "-p", ".splunk-access"), cmd("chmod", "700", ".splunk-access")]      # must exist (owner-only) before the read-only mount, or Docker would create it as root
    if cfg.splunk.mode == "bundled":
        out.append(cmd("sh", "scripts/hec-certs.sh", AGENTSEC_HEC_TLS_MODE="LOCAL_SELF_SIGNED"))         # without it Docker would create ./.certs/hec.pem as a directory
    if cfg.gateway.enabled and not gateway_dir_exists:
        out.append(cmd("sh", "scripts/gateway.sh", "init", AGENTSEC_PUBLIC_HOST=cfg.gateway.host, AGENTSEC_PUBLIC_PORT=str(cfg.gateway.port)))   # gateway.sh reads the process environment, not .env; skipped when .gateway exists (init refuses to overwrite)
    if cfg.gateway.enabled and cfg.gateway.ctf:
        out.append(cmd("sh", "scripts/gateway.sh", "ctf-enable"))     # idempotent: keeps an existing secret, checks owner and mode, creates the 0700 state directory
    return out


def build_plan(cfg: InstallConfig, locks: Locks, facts: dict, previous_env: dict | None = None) -> Plan:
    sec = generate_secrets(previous_env)
    values = env_values(cfg, locks, sec)
    override = render_override(cfg)
    models, _ = resolve_models(cfg, locks)
    refs = {}
    if cfg.splunk.mode == "bundled":
        refs["splunk"] = splunk_image(cfg, locks)[0]
    if cfg.ollama.mode == "bundled":
        refs["ollama"] = ollama_image(cfg, locks)[0]
    svc = services(cfg)
    state = {"schema": 1, "installer": INSTALLER_VERSION, "config": cfg.to_dict(), "resolved": {"images": refs, "models": models, "services": svc,
             "compose_files": values["COMPOSE_FILE"].split(":")}, "detected": {k: facts.get(k) for k in ("platform", "volume_prefixes")}}
    env_text = render_env(values)
    state["files"] = {".env": hashlib.sha256(env_text.encode()).hexdigest(), f"{STATE_DIR}/compose.override.yml": hashlib.sha256(override.encode()).hexdigest()}
    files = {".env": env_text, f"{STATE_DIR}/compose.override.yml": override, f"{STATE_DIR}/install.json": json.dumps(state, indent=2, sort_keys=True) + "\n"}
    plan = Plan(files=files, services=svc)
    plan.downloads = [{"what": f"{k} image", "ref": r} for k, r in refs.items()] + \
                     ([{"what": f"model {n}", "ref": n} for n in sorted(set(models.values()))] if cfg.ollama.mode == "bundled" else [])   # only the bundled Ollama container pulls; a host or remote Ollama is yours to fill
    plan.ports = {"gateway": cfg.gateway.port} if cfg.gateway.enabled else {k: getattr(cfg.ports, k) for k in ("acmebank", "attack")}
    plan.commands = [{"argv": ["docker", "compose", "config", "-q"], "env": {}}] + prestart_commands(cfg, bool(facts.get("gateway_dir_exists")))
    pull = [x for x in svc if x in ("splunk", "ollama")]
    if pull:
        plan.commands.append({"argv": ["docker", "compose", "pull", *pull], "env": {}})
    plan.commands.append({"argv": ["docker", "compose", "up", "-d", *svc], "env": {}})
    plan.notes = []
    if cfg.naming == "project":
        plan.notes.append("project-scoped container names: lab-up.sh, lab-ready.sh, lab-down.sh, lab-preflight.sh and gateway-ready.sh find containers by Compose service; other helper scripts under scripts/ still address the fixed agentsec_* names and need the legacy naming (see docs/INSTALLER.md). Manage the lab with `agentsec up|down|status|logs`.")
    if cfg.ollama.mode == "bundled" and not refs.get("ollama", "").count("@"):
        plan.notes.append("the bundled Ollama image is not pinned by digest (floating tag).")
    return plan
